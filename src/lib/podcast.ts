/** Create or replace the feed token. The server shows it only once. */
export async function createFeedToken(): Promise<string> {
  return (await call<{ token: string }>('/feed-token', { method: 'POST' })).token;
}

export async function revokeFeedToken(): Promise<void> {
  await call('/feed-token', { method: 'DELETE' });
}

export function podcastFeedUrl(token: string, showId: string): string {
  return apiUrl(`/api/podcasts/feed/${encodeURIComponent(token)}/${showId}`);
}

/** The episode a podcast lesson was generated by, from its sourceMeta. */
export function podcastEpisodeIdOf(
  lesson: Pick<Lesson, 'sourceType' | 'sourceMeta'> | null,
): string | null {
  if (!lesson || lesson.sourceType !== 'podcast' || !lesson.sourceMeta) return null;
  try {
    const meta = JSON.parse(lesson.sourceMeta) as { episodeId?: unknown };
    return typeof meta.episodeId === 'string' ? meta.episodeId : null;
  } catch {
    return null;
  }
}

/** Paragraph numbers 1..count, the choices of a range picker. */
export function paragraphChoices(count: number): number[] {
  return Array.from({ length: Math.max(0, count) }, (_, i) => i + 1);
}

/** "1 h 05 min" or "12 min". */
export function formatMinutes(minutes: number): string {
  if (minutes < 60) return `${minutes} min`;
  const hours = Math.floor(minutes / 60);
  return `${hours} h ${String(minutes % 60).padStart(2, '0')} min`;
}

