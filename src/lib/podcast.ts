export class PodcastError extends Error {
  constructor(
    message: string,
    readonly code?: string,
  ) {
    super(message);
  }
}

async function call<T>(path: string, init?: RequestInit): Promise<T> {
  const separator = path.includes('?') ? '&' : '?';
  const res = await apiFetch(`/api/podcasts${path}${separator}language=${getActiveLanguage()}`, {
    ...init,
    headers: init?.body ? { 'Content-Type': 'application/json' } : undefined,
  });
  if (!res.ok) {
    const data = (await res.json().catch(() => ({}))) as { error?: string; code?: string };
    const message =
      data.error === 'plan_limit'
        ? 'Your plan’s limit is reached.'
        : data.error || 'Something went wrong';
    throw new PodcastError(
      message,
      data.code ?? (data.error === 'plan_limit' ? 'PLAN_LIMIT' : undefined),
    );
  }
  return res.json() as Promise<T>;
}

export function getPodcasts(): Promise<PodcastOverview> {
  return call<PodcastOverview>('');
}

export function estimatePodcast(range: PodcastRange): Promise<PodcastEstimate> {
  return call<PodcastEstimate>('/estimate', { method: 'POST', body: JSON.stringify(range) });
}

export async function createPodcast(
  range: PodcastRange & { engine: PodcastEngineId },
): Promise<PodcastEpisode> {
  const { episode } = await call<{ episode: PodcastEpisode }>('', {
    method: 'POST',
    body: JSON.stringify(range),
  });
  invalidateCollections();
  return episode;
}

export async function getPodcastEpisode(id: string): Promise<PodcastEpisode | null> {
  try {
    return (await call<{ episode: PodcastEpisode }>(`/${id}`)).episode;
  } catch {
    return null;
  }
}

export async function retryPodcast(id: string): Promise<PodcastEpisode> {
  return (await call<{ episode: PodcastEpisode }>(`/${id}/retry`, { method: 'POST' })).episode;
}

export async function deletePodcast(id: string): Promise<void> {
  await call(`/${id}`, { method: 'DELETE' });
  invalidateCollections();
}

